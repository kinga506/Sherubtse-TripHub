const router=require('express').Router();
const controller=require('../controllers/authController');
const {authLimiter,resendLimiter,requireAuth}=require('../middleware/security');
router.get('/signup',controller.showSignup);
router.post('/signup',authLimiter,controller.signup);
router.get('/verify',controller.verify);
router.get('/login',controller.showLogin);
router.post('/login',authLimiter,controller.login);
router.post('/logout',requireAuth,controller.logout);
router.get('/resend-verification',controller.showResend);
router.post('/resend-verification',resendLimiter,controller.resend);
const password=require('../controllers/passwordController');
router.get('/forgot-password',password.showForgot);
router.post('/forgot-password',authLimiter,password.forgot);
router.get('/reset-password',password.showReset);
router.post('/reset-password',authLimiter,password.reset);
router.get('/change-password',requireAuth,password.showChange);
router.post('/change-password',requireAuth,authLimiter,password.change);
module.exports=router;
